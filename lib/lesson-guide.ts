export function getLessonGuide(slot: LessonSlot): LessonGuide {
  if (hasTopicSpecificPractice(slot)) {
    const task = createPracticeTasks(slot)[0];
    const objective = topicObjective(slot.topic);
    const taskOptions = task.options ?? [
      { value: String(Number(task.answer) - 1), ru: String(Number(task.answer) - 1), ky: String(Number(task.answer) - 1) },
      { value: task.answer, ru: task.answer, ky: task.answer },
      { value: String(Number(task.answer) + 1), ru: String(Number(task.answer) + 1), ky: String(Number(task.answer) + 1) },
    ];
    return {
      visual: task.visual ?? "",
      fruitGroups: task.fruitGroups,
      steps: [
        objective,
        task.hint,
        text("Реши пример, затем проверь ответ по объяснению.", "Мисалды чыгарып, анан түшүндүрмө менен жоопту текшер."),
      ],
      example: task.explanation,
      prompt: task.prompt,
      options: taskOptions.map((item) => choice(item.value, item.ru, item.ky)),
      answer: task.answer,
      feedback: task.explanation,
    };
  }

  if (slot.topic.family === "numbers" && slot.grade === 2 && /рим/i.test(slot.topic.titleRu)) {
    return {
      visual: "I　II　III　IV　V",
      steps: [
        text("Римские цифры записывают числа буквами-символами.", "Рим цифралары сандарды белгилер менен жазат."),
        text("I означает 1, V означает 5, X означает 10.", "I — 1ди, V — 5ти, X — 10ду билдирет."),
        text("Когда меньший знак стоит перед большим, его вычитают: IV — это 4.", "Кичине белги чоң белгинин алдында турса, аны кемитебиз: IV — бул 4."),
      ],
      example: text("VI = 5 + 1 = 6.", "VI = 5 + 1 = 6."),
      prompt: text("Сколько означает римская запись IV?", "IV деген рим жазуусу канчаны билдирет?"),
      options: [choice("4", "4", "4"), choice("6", "6", "6"), choice("11", "11", "11")],
      answer: "4",
      feedback: text("I стоит перед V, поэтому 5 − 1 = 4.", "I белгиси Vнин алдында турат, ошондуктан 5 − 1 = 4."),
    };
  }

  if (slot.topic.family === "place-value" && slot.grade === 2) {
    const guide = guides["place-value"];
    return {
      ...guide,
      visual: "3 десятка + 4 единицы = 34",
      example: text("34 — это 3 десятка и 4 единицы.", "34 — бул 3 ондук жана 4 бирдик."),
      prompt: text("Сколько десятков в числе 24?", "24 санында канча ондук бар?"),
      options: [choice("2", "2 десятка", "2 ондук"), choice("4", "4 десятка", "4 ондук"), choice("24", "24 десятка", "24 ондук")],
      answer: "2",
      feedback: text("Первая цифра числа 24 показывает 2 десятка.", "24 санынын биринчи цифрасы 2 ондукту көрсөтөт."),
    };
  }

  if (slot.topic.family === "measurement" && /термометр/i.test(slot.topic.titleRu)) {
    return {
      ...guides.measurement,
      visual: "❄️　0°　🌤️　10°",
      steps: [
        text("Термометр показывает температуру.", "Термометр температураны көрсөтөт."),
        text("Найди, у какой отметки остановился столбик или указатель.", "Көрсөткүч кайсы белгиге жеткенин тап."),
        text("Чем число выше, тем теплее; чем ниже, тем холоднее.", "Сан канчалык чоң болсо, ошончолук жылуу; кичине болсо, ошончолук суук."),
      ],
      example: text("Если указатель стоит на 10°, температура равна десяти градусам.", "Көрсөткүч 10° белгисинде турса, температура он градус болот."),
      prompt: text("Указатель термометра стоит на 5°. Сколько градусов он показывает?", "Термометрдин көрсөткүчү 5° белгисинде. Канча градусту көрсөтөт?"),
      options: [choice("0", "0°", "0°"), choice("5", "5°", "5°"), choice("10", "10°", "10°")],
      answer: "5",
      feedback: text("Верно: смотрим на отметку указателя — это 5°.", "Туура: көрсөткүч турган белгини окуйбуз — бул 5°."),
    };
  }

  if (slot.topic.family === "measurement" && /деньги|цена|стоимость|акч|баа|нарк/i.test(`${slot.topic.titleRu} ${slot.topic.titleKy}`)) {
    return {
      ...guides.measurement,
      visual: "2 сом + 3 сом = 5 сом",
      steps: [
        text("Цена показывает, сколько стоит один предмет.", "Баа бир буюм канча турарын көрсөтөт."),
        text("Стоимость нескольких одинаковых предметов — это цена, повторённая нужное число раз.", "Бир нече бирдей буюмдун наркы — бааны буюмдардын санына жараша кошуу."),
        text("Складывай деньги в одной и той же единице и подпиши ответ.", "Акчаларды бирдей бирдик менен кошуп, жоопко бирдигин жаз."),
      ],
      example: text("Два карандаша по 3 сома: 3 + 3 = 6 сомов.", "Ар бири 3 сомдон турган эки калем: 3 + 3 = 6 сом."),
      prompt: text("Одна тетрадь стоит 2 сома. Сколько стоят две такие тетради?", "Бир дептер 2 сом турат. Ушундай эки дептер канча турат?"),
      options: [choice("2", "2 сома", "2 сом"), choice("4", "4 сома", "4 сом"), choice("6", "6 сом", "6 сом")],
      answer: "4",
      feedback: text("Две тетради по 2 сома: 2 + 2 = 4 сома.", "2 сомдон эки дептер: 2 + 2 = 4 сом."),
    };
  }

  if (slot.topic.family === "word-problems" && /во много раз|эсе/i.test(`${slot.topic.titleRu} ${slot.topic.titleKy}`)) {
    return {
      ...guides["word-problems"],
      visual: "3　→　в 2 раза больше　→　?",
      steps: [
        text("Слова «в несколько раз больше» означают одинаковые группы.", "«Бир нече эсе көп» деген сөз бирдей топторду билдирет."),
        text("Узнай, сколько предметов в одной группе и сколько таких групп.", "Бир топто канча буюм жана канча топ бар экенин аныкта."),
        text("Умножь количество в одной группе на число групп.", "Бир топтогу буюмдардын санын топтордун санына көбөйт."),
      ],
      example: text("В 2 раза больше, чем 3: две тройки, 3 + 3 = 6.", "3төн 2 эсе көп: эки үчтүк, 3 + 3 = 6."),
      prompt: text("В 2 раза больше, чем 4 — это сколько?", "4төн 2 эсе көп болсо, канча болот?"),
      options: [choice("6", "6", "6"), choice("8", "8", "8"), choice("4", "4", "4")],
      answer: "8",
      feedback: text("Два раза по 4: 4 + 4 = 8.", "4төн эки жолу: 4 + 4 = 8."),
    };
  }

  return guides[slot.topic.family];
}
